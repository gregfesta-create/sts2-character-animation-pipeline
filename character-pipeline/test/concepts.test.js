'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const {
  materializeConcept
} = require('../lib/concepts');
const {
  createSpec
} = require('../lib/spec');
const {
  publishSource
} = require('../lib/assets');
test('supplied original concept is reviewed unchanged without generating a replacement', async t => {
  const scratch = path.resolve(__dirname, '../../.tmp/concepts');
  await fs.mkdir(scratch, {
    recursive: true
  });
  const root = await fs.mkdtemp(path.join(scratch, 'supplied-'));
  t.after(() => fs.rm(root, {
    recursive: true,
    force: true
  }));
  const jobRoot = path.join(root, 'job');
  await fs.writeFile(path.join(root, 'original.png'), 'existing character artwork');
  const saved = await publishSource(root, 'original.png', jobRoot);
  const record = {
    relative: 'sources/' + saved.hash,
    hash: saved.hash,
    size: saved.size
  };
  const spec = createSpec({
    id: 'robot',
    description: 'animate my existing robot',
    template: 'mechanical'
  });
  spec.artwork = {
    provider: 'comfyui',
    source: 'original.png',
    prompt: 'Keep this robot'
  };
  const result = await materializeConcept(spec, {
    jobRoot,
    config: {
      sourceRoots: [root],
      outputRoot: root
    },
    inputs: {
      'original.png': record
    },
    version: 'fixture',
    createComfyProvider: () => {
      throw new Error('Must not replace supplied original');
    }
  });
  assert.equal(result.record.hash, saved.hash);
  assert.equal(await fs.readFile(result.path, 'utf8'), 'existing character artwork');
});
test('concepts retain original generated bytes and reuse matching immutable results', async t => {
  const scratch = path.resolve(__dirname, '../../.tmp/concepts');
  await fs.mkdir(scratch, {
    recursive: true
  });
  const root = await fs.mkdtemp(path.join(scratch, 'job-'));
  t.after(() => fs.rm(root, {
    recursive: true,
    force: true
  }));
  const spec = createSpec({
    id: 'robot',
    description: 'robot concept',
    template: 'mechanical'
  });
  spec.artwork = {
    provider: 'comfyui',
    prompt: 'robot',
    seed: 12
  };
  let calls = 0;
  let request;
  const options = {
    jobRoot: root,
    config: {
      sourceRoots: [root],
      outputRoot: root,
      comfyui: {
        checkpoint: 'local-model'
      }
    },
    inputs: {},
    version: 'fixture-v1',
    createComfyProvider: async ({
      stagingDir,
      checkpoint
    }) => ({
      run: async value => {
        request = value;
        calls++;
        await checkpoint.save({
          status: 'complete',
          promptId: 'fixture'
        });
        await fs.mkdir(stagingDir, {
          recursive: true
        });
        const file = path.join(stagingDir, 'original.png');
        await fs.writeFile(file, 'original generated fixture bytes');
        return {
          images: [{
            path: file
          }],
          provenance: {
            seed: value.seed
          }
        };
      }
    })
  };
  const first = await materializeConcept(spec, options);
  assert.equal(request.prompt.includes('robot'), true);
  assert.equal(request.seed, 12);
  assert.equal(first.record.relative.startsWith('sources/'), true);
  assert.equal(await fs.readFile(first.path, 'utf8'), 'original generated fixture bytes');
  assert.equal((await materializeConcept(spec, options)).record.hash, first.record.hash);
  assert.equal(calls, 1);
  spec.style.shading = 'flat';
  await materializeConcept(spec, options);
  assert.equal(calls, 2);
});
test('concept quota failure retains prompt identity but cleans generated candidates before source publication', async t => {
  const scratch = path.resolve(__dirname, '../../.tmp/concepts');
  await fs.mkdir(scratch, {
    recursive: true
  });
  const root = await fs.mkdtemp(path.join(scratch, 'quota-'));
  t.after(() => fs.rm(root, {
    recursive: true,
    force: true
  }));
  const spec = createSpec({
    id: 'robot',
    description: 'quota fixture',
    template: 'custom'
  });
  spec.artwork = {
    provider: 'comfyui',
    prompt: 'fixture'
  };
  const options = {
    jobRoot: root,
    config: {
      outputRoot: root,
      sourceRoots: [root],
      limits: {
        maxStorageBytes: 160
      }
    },
    inputs: {},
    version: 'fixture',
    createComfyProvider: async ({
      stagingDir,
      checkpoint
    }) => ({
      run: async () => {
        await checkpoint.save({
          promptId: 'owned-prompt',
          status: 'completed'
        });
        await fs.mkdir(stagingDir, {
          recursive: true
        });
        const file = path.join(stagingDir, 'candidate.png');
        await fs.writeFile(file, Buffer.alloc(100));
        return {
          images: [{
            path: file
          }],
          provenance: {}
        };
      }
    })
  };
  await assert.rejects(materializeConcept(spec, options), {
    code: 'QUOTA_EXCEEDED'
  });
  const sources = await fs.readdir(path.join(root, 'sources')).catch(cause => {
    if (cause.code === 'ENOENT') return [];
    throw cause;
  });
  assert.deepEqual(sources, []);
  const folders = await fs.readdir(path.join(root, 'provider/concepts'));
  assert.deepEqual(await fs.readdir(path.join(root, 'provider/concepts', folders[0])), ['receipt.json']);
});
